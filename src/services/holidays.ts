export function findHoliday(id: string | null | undefined): Holiday | undefined {
  return id ? HOLIDAYS.find((h) => h.id === id) : undefined;
}

/** Следващият празник в учебната година спрямо днешния месец. */
export function upcomingHoliday(now: Date = new Date()): Holiday {
  const order = (m: number) => (m >= 9 ? m - 9 : m + 3); // септември = 0 … август = 11
  const cur = order(now.getMonth() + 1);
  return HOLIDAYS.find((h) => order(h.month) >= cur) ?? HOLIDAYS[0]!;
}
