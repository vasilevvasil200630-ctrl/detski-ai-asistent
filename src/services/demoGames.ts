import { AgeGroup, GeneratedGame, GroupMood, PlayResources } from '../types';

/**
 * Вграден демо генератор на ситуационни игри (работи без API ключ и без интернет).
 *
 * Всяко генериране връща 3 игри от 3 различни „чекмеджета“:
 *   1. Подвижно-регулираща игра според настроението (шумни / уморени / разсеяни)
 *   2. Дидактична / словесна игра с гатанка или броилка
 *   3. Екипна игра според наличните ресурси
 * При всяко ново натискане на „Генерирай“ чекмеджетата се завъртат,
 * така че повторно генериране с едни и същи филтри дава нови игри.
 */

export interface DemoContext {
  ageGroup: AgeGroup;
  ageShort: string;
  ageRange: string;
  mood: GroupMood;
  moodTag: string;
  moodGoalFocus: string;
  locLabel: string;
  spatialHint: string;
  isYard: boolean;
  durLabel: string;
  pacingHint: string;
  resources: PlayResources;
  resLabel: string;
  toolName: string;
  kw?: string;
}

interface DemoTemplate {
  title: (c: DemoContext) => string;
  rhymeTitle?: string;
  rhyme: string[];
  steps: (c: DemoContext) => string[];
  goal: (c: DemoContext) => string;
  sop: string;
  tip: string;
}

const onTheme = (c: DemoContext, text: string, fallback = '') => (c.kw ? text.replace('{kw}', c.kw) : fallback);

