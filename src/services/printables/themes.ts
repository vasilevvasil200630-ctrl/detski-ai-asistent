const norm = (s: string) => s.toLowerCase().replace(/ѝ/g, 'и');
/** „ябълка“ → „ябълк“ (хваща „ябълки“, „ябълката“); кратките думи — цели („кон“, „лъв“). */
const stemOf = (word: string) => (word.length > 4 ? word.slice(0, -1) : word);

