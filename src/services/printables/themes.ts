/** Думи, които не са „главен предмет“ (Ден на Земята е за природата, не за космоса). */
const NO_FOCUS = new Set(['земя']);

type Entry = { stem: string; pic: Pic; themeId: string };
/** Речник „дума → картинка и тема“; по-дългите думи са първи („ракета“ преди „рак“). */
const LEXICON: Entry[] = [
  ...THEMES.flatMap((t) => t.pics.map((pic) => ({ word: norm(pic.w), pic, themeId: t.id }))),
  ...EXTRA.map(([pic, themeId]) => ({ word: norm(pic.w), pic, themeId })),
]
  .filter((e) => !NO_FOCUS.has(e.word))
  .filter((e, i, all) => {
    const home = HOME[e.word];
    const first = all.findIndex((x) => x.word === e.word && (!home || x.themeId === home));
    return first === i;
  })
  .map((e) => ({ stem: stemOf(e.word), pic: e.pic, themeId: e.themeId }))
  .sort((a, b) => b.stem.length - a.stem.length);

/** Главният предмет в темата („Ябълка“, „Ябълките в градината“ → 🍎 ябълка, тема „food“). */
export function focusFor(topic: string): { pic: Pic; themeId: string } | null {
  const words = norm(topic)
    .split(/[^\p{L}]+/u)
    .filter((w) => w.length >= 3);
  for (const w of words) {
    // Дълги думи, които само започват с кратък корен („конструиране“ не е „кон“), не се броят
    const hit = LEXICON.find((e) => w.startsWith(e.stem) && w.length <= e.stem.length * 2 + 2);
    if (hit) return { pic: hit.pic, themeId: hit.themeId };
  }
  return null;
}

/**
 * Темата на листа: по главния предмет (той е първата картинка и присъства във всяка задача),
 * иначе по ключовите думи, иначе общ набор.
 */
export function themeFor(topic: string): Theme {
  const focus = focusFor(topic);
  if (focus) {
    const base = THEMES.find((t) => t.id === focus.themeId)!;
    return { ...base, focus: focus.pic, pics: [focus.pic, ...base.pics.filter((x) => x.e !== focus.pic.e)] };
  }
  const t = norm(topic);
  return THEMES.find((th) => th.keys.some((k) => t.includes(k))) ?? { id: 'default', keys: [], pics: DEFAULT_PICS };
}

/**
 * Ред към модела: темата е задължителна за всяка задача, с подходящите картинки и главния предмет.
 * Без разпозната тема — само изискването.
 */
export function topicRule(topic: string): string {
  const t = topic.trim();
  if (!t) return '';
  const theme = themeFor(t);
  const lines = [
    `ТЕМАТА Е ЗАДЪЛЖИТЕЛНА: всичко е за „${t}“. Всяка задача и всяка картинка са по тази тема (единственото изключение е излишната картинка в „odd“). Не слагай картинки без връзка с темата.`,
  ];
  if (theme.focus) lines.push(`Главният предмет „${theme.focus.e} ${theme.focus.w}“ присъства във всяка задача с картинки.`);
  if (theme.id !== 'default') lines.push(`Подходящи картинки: ${theme.pics.map((x) => `${x.e} ${x.w}`).join(', ')} (може и други от същата тема).`);
  return lines.join('\n');
}

/** Корените на думите в темата — за проверка дали задача от модела е по темата. */
export function themeStems(theme: Theme): string[] {
  return theme.id === 'default' ? [] : theme.pics.map((x) => stemOf(norm(x.w)));
}

