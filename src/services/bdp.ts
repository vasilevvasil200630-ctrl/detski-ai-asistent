export function findBdpTheme(ageGroup: AgeGroup, name: string | undefined): BdpTheme | undefined {
  if (!name) return undefined;
  const n = name.trim().toLowerCase();
  return BDP_THEMES[ageGroup].find((t) => t.theme.toLowerCase() === n);
}

/** Кратък текст за промптовете. */
export function bdpPromptRules(ageGroup: AgeGroup): string {
  const r = BDP_NAREDBA5_RESULTS[ageGroup];
  return [
    `БДП по Наредба № 5: не е отделно направление — интегрира се основно в „${BDP.host.direction}“ (ядро „${BDP.host.core}“) и в „Конструиране и технологии“ (ядро „Техника“), или в допълнителни форми.`,
    `Очаквани резултати за групата: ${r.world} ${r.technika}`,
    `Теми за групата (${BDP.source}): ${BDP_THEMES[ageGroup].map((t) => `„${t.theme}“`).join(', ')}; минимум ${BDP_MIN_PER_YEAR[ageGroup]} педагогически ситуации по БДП за годината.`,
  ].join('\n');
}
