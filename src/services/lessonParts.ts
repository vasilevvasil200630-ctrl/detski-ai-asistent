const lower = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const dot = (s: string) => (/[.!?]$/.test(s) ? s : `${s}.`);

/** Трите задачи: образователна (от първия резултат), развиваща и възпитателна. */
export function lessonTasks(direction: EducationalDirection | 'bdp', results: string[]): string[] {
  const first = results[0];
  return [
    first ? `Образователна: детето да ${lower(dot(first))}` : 'Образователна: обогатяване на представите по темата.',
    `Развиваща: развиване на ${DEVELOPING[direction]}.`,
    `Възпитателна: ${UPBRINGING[direction]}.`,
  ];
}

const words = (s: string) => [...new Set(s.toLowerCase().split(/[^\p{L}]+/u).filter((w) => w.length >= 4))];

/** Една и съща дума в различна форма: „брои“ и „броят“, „цифра“ и „цифрата“. */
function sameWord(a: string, b: string): boolean {
  let n = 0;
  while (n < a.length && n < b.length && a[n] === b[n]) n++;
  return n >= 4 || (n >= 3 && a.length <= 6 && b.length <= 6);
}

/**
 * До три очаквани резултата за ядрото и групата — дословно от Наредбата, подбрани по това,
 * което играта прави (общи думи с текста на играта). Редът е като в приложението.
 */
export function pickResults(direction: EducationalDirection, core: string, ageGroup: AgeGroup, about: string, max = 3): string[] {
  const all = expectedResults(direction, core, ageGroup);
  if (all.length <= max) return all;
  const text = words(about);
  const scored = all.map((r, i) => ({ r, i, score: words(r).filter((w) => text.some((t) => sameWord(w, t))).length }));
  const best = [...scored].sort((a, b) => b.score - a.score || a.i - b.i).slice(0, max);
  return best.sort((a, b) => a.i - b.i).map((x) => x.r);
}

/** Как учителят проверява резултатите — според вида на ситуацията. */
export function assessmentText(type: SituationType, results: string[]): string {
  const what = results.length ? ` дали всяко дете ${results.map((r) => lower(r.replace(/[.;]$/, ''))).join('; ')}` : ' как се справя всяко дете';
  return type === 'check'
    ? `Учителят наблюдава поотделно${what}. Отбелязва резултата в картата за наблюдение на групата (постига, постига с помощ, не постига още).`
    : `По време на играта учителят наблюдава${what}. Децата, които се затрудняват, получават още една игра по същото ядро в допълнителните форми.`;
}

