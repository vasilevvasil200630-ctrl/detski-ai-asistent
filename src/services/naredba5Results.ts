const GROUP_INDEX: Record<AgeGroup, 0 | 1 | 2 | 3> = { '1': 0, '2': 1, '3': 2, '4': 3 };

/** Очакваните резултати по ядро за групата (празен масив — наредбата няма за тази група). */
export function expectedResults(direction: EducationalDirection, core: string, ageGroup: AgeGroup): string[] {
  return RESULTS[direction]?.[core]?.[GROUP_INDEX[ageGroup]] ?? [];
}

/** Всички ядра на направлението с резултатите им за групата (само ядрата, които имат резултати). */
export function resultsForGroup(direction: EducationalDirection, ageGroup: AgeGroup): { core: string; results: string[] }[] {
  return Object.entries(RESULTS[direction])
    .map(([core, byGroup]) => ({ core, results: byGroup[GROUP_INDEX[ageGroup]] }))
    .filter((c) => c.results.length > 0);
}

/** Дали текстът е точно един от очакваните резултати (защита срещу измислени „задачи“ от заявката). */
export function isExpectedResult(direction: EducationalDirection, core: string, ageGroup: AgeGroup, text: string): boolean {
  return expectedResults(direction, core, ageGroup).includes(text);
}
