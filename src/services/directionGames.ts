/** Играта за точно това ядро — за основната част на вградения план-конспект. */
export function gameForCore(direction: LessonDirection, core: string, kw: string, ageGroup: AgeGroup): { title: string; steps: string[]; skills: string } | null {
  const t = T[direction].find((x) => x.core.replace(' (БДП)', '') === core);
  if (!t) return null;
  const c = { ageGroup, isYard: false } as DemoContext;
  return { title: t.title(kw), steps: t.steps(kw, c), skills: t.skills };
}

/** Всички ядра, за които има вградена игра (за проверките). */
export function coresWithGames(direction: LessonDirection): string[] {
  return [...new Set(T[direction].map((x) => x.core.replace(' (БДП)', '')))];
}

let turn = 0;

/** Три игри от избраното направление (въртят се при всяко генериране). */
export function buildDirectionGames(c: DemoContext, direction: LessonDirection): GeneratedGame[] {
  const preferred = T[direction].filter((t) => c.preferCores?.includes(t.core.replace(' (БДП)', '')));
  // Първо игрите по ядрата на избраните задачи, после останалите
  const pool = preferred.length ? [...preferred, ...T[direction].filter((t) => !preferred.includes(t))] : T[direction];
  const v = preferred.length ? 0 : turn++;
  const kw = c.kw?.trim() || 'нашата тема';
  const stamp = Date.now();
  const colors: GeneratedGame['badgeColor'][] = ['mint', 'lavender', 'coral'];
  return [0, 1, 2].map((i) => {
    const t = pool[(v + i) % pool.length]!;
    return {
      id: `dg-${direction}-${stamp}-${v}-${i}`,
      title: t.title(kw),
      subtitle: `${DIRECTION_TEXT[direction]} · ${c.ageShort} · ${c.locLabel}`,
      tags: [DIRECTION_TEXT[direction], t.core, c.ageRange],
      badgeColor: colors[i]!,
      rhymeTitle: 'Стихче за начало:',
      rhymeLines: t.rhyme,
      steps: t.steps(kw, c),
      pedagogicalGoal: `${direction === 'bdp' ? 'Околен свят' : DIRECTION_TEXT[direction]} (ядро „${t.core.replace(' (БДП)', '')}“)${direction === 'bdp' ? ', тема по БДП' : ''}: ${t.skills}.`,
      sopAdaptation: t.sop,
      teacherTip: t.tip,
    };
  });
}
